/**
 * Builds the pre-recorded voice pack used by talk-back, so spoken UI feedback
 * starts instantly instead of waiting on a network synthesis round trip.
 *
 *   node scripts/build-voice-pack.mjs            # synthesize only what is missing
 *   node scripts/build-voice-pack.mjs --dry      # list phrases, no audio
 *
 * Outputs:
 *   src/services/talkPhrases.js + mobile/src/services/talkPhrases.js (TP, voiceKey, spokenForm)
 *   public/voice/<key>.mp3 + public/voice/index.json                 (web)
 *   mobile/assets/voice/<key>.mp3 + mobile/src/services/voicePack.js (native)
 */
import { copyFileSync, existsSync, mkdirSync, readdirSync, readFileSync, statSync, unlinkSync, writeFileSync } from 'node:fs'
import { join, extname } from 'node:path'
import handler from '../api/tts.js'

const VOICE = 'km-KH-SreymomNeural'
const MAX_SCANNED_LEN = 64
const DRY = process.argv.includes('--dry')
const KHMER = /[ក-៿]/g

// Keep in sync with the generated talkPhrases.js (written below from these sources).
const VOICE_KEY_SRC = `export const voiceKey = (text) => {
  let h = 0x811c9dc5
  for (let i = 0; i < text.length; i++) {
    h ^= text.charCodeAt(i)
    h = Math.imul(h, 0x01000193)
  }
  return (h >>> 0).toString(16).padStart(8, '0')
}`

const SPOKEN_FORM_SRC = `// What is actually said for a label: English helper notes in brackets are for
// sighted/dev readers and are dropped, as are links and extra whitespace.
export const spokenForm = (text) =>
  String(text || '')
    .replace(/\\s*\\((?=[^()]*[A-Za-z])[^()]*\\)/g, '')
    .replace(/https?:\\/\\/\\S+/g, '')
    .replace(/\\s+/g, ' ')
    .trim()`

const voiceKey = new Function(`${VOICE_KEY_SRC.replace('export const', 'const')}; return voiceKey`)()
const spokenForm = new Function(`${SPOKEN_FORM_SRC.replace('export const', 'const')}; return spokenForm`)()

const phrases = JSON.parse(readFileSync('scripts/talk-phrases.json', 'utf8'))

function writeTalkPhrases(path) {
  const tp = Object.fromEntries(Object.entries(phrases).map(([k, v]) => [k, v]))
  writeFileSync(
    path,
    `// GENERATED by scripts/build-voice-pack.mjs from scripts/talk-phrases.json. Do not edit.\n\n` +
      `${VOICE_KEY_SRC}\n\n${SPOKEN_FORM_SRC}\n\n` +
      `export const TP = ${JSON.stringify(tp, null, 2)}\n`
  )
}
writeTalkPhrases('src/services/talkPhrases.js')
writeTalkPhrases('mobile/src/services/talkPhrases.js')

// --- Phrase set: every named phrase plus short Khmer literals found in the UI code ---
function walk(dir, out = []) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name)
    if (statSync(p).isDirectory()) walk(p, out)
    else if (['.js', '.vue'].includes(extname(p)) && !/(sampleLibrary|khmerNormalizer|khmerOcrCorrector|voiceCommands|talkPhrases|voicePack)\.js$/.test(p)) out.push(p)
  }
  return out
}

const wanted = new Map() // key -> text
const add = (raw, named = false) => {
  const text = spokenForm(raw)
  if (named) {
    if (text) wanted.set(voiceKey(text), text)
    return
  }
  if (text.length < 2 || text.length > MAX_SCANNED_LEN) return
  if (/[{}=<>|?;`\\]/.test(text)) return
  const khmer = (text.match(KHMER) || []).length
  const letters = text.replace(/[\s\d.,:។៖\-]/g, '').length
  if (!khmer || khmer / letters < 0.5) return
  wanted.set(voiceKey(text), text)
}

for (const p of Object.values(phrases)) add(p.km, true)
for (const root of ['src', 'mobile/src']) {
  for (const file of walk(root)) {
    const src = readFileSync(file, 'utf8')
    const re = /'([^'\n]*)'|"([^"\n]*)"|`([^`\n]*)`|>([^<>{}\n]*)</g
    let m
    while ((m = re.exec(src))) {
      const s = m[1] ?? m[2] ?? m[3] ?? m[4] ?? ''
      if (s.includes('${') || s.includes('{{')) continue
      // A bare sentence may contain several clauses split by the danda: pack each one too
      add(s)
      if (s.includes('។')) s.split('។').forEach((part) => add(part))
    }
  }
}

console.log(`${wanted.size} phrases in the pack`)
if (DRY) process.exit(0)

mkdirSync('public/voice', { recursive: true })
mkdirSync('mobile/assets/voice', { recursive: true })

let ipSeq = 0
async function synth(text) {
  return new Promise((resolve, reject) => {
    const res = {
      code: 200,
      setHeader() {},
      status(c) { this.code = c; return this },
      json(o) { reject(new Error(`tts ${this.code} ${JSON.stringify(o)}`)) },
      send(buf) { resolve(buf) },
    }
    // The handler rate-limits per IP; a distinct fake address per call keeps the batch moving.
    handler({ method: 'POST', headers: { 'x-forwarded-for': `10.9.${(ipSeq >> 8) & 255}.${ipSeq++ & 255}` }, body: { text, voice: VOICE } }, res).catch(reject)
  })
}

const todo = [...wanted].filter(([key]) => !existsSync(`public/voice/${key}.mp3`))
console.log(`${todo.length} to synthesize`)
let done = 0
const failed = []
async function worker() {
  while (todo.length) {
    const [key, text] = todo.shift()
    let ok = false
    for (let attempt = 0; attempt < 3 && !ok; attempt++) {
      try {
        const audio = await synth(text)
        writeFileSync(`public/voice/${key}.mp3`, audio)
        ok = true
      } catch (e) {
        if (attempt === 2) failed.push([text, String(e.message || e)])
      }
    }
    if (++done % 25 === 0) console.log(`  ${done} done`)
  }
}
await Promise.all([worker(), worker(), worker(), worker()])

// Drop recordings of phrases that no longer exist, so the pack never grows stale
for (const dir of ['public/voice', 'mobile/assets/voice']) {
  for (const name of readdirSync(dir)) {
    if (name.endsWith('.mp3') && !wanted.has(name.slice(0, -4))) unlinkSync(join(dir, name))
  }
}

const keys = [...wanted.keys()].filter((k) => existsSync(`public/voice/${k}.mp3`)).sort()
for (const k of keys) {
  if (!existsSync(`mobile/assets/voice/${k}.mp3`)) copyFileSync(`public/voice/${k}.mp3`, `mobile/assets/voice/${k}.mp3`)
}
writeFileSync('public/voice/index.json', JSON.stringify(keys))
writeFileSync(
  'mobile/src/services/voicePack.js',
  `// GENERATED by scripts/build-voice-pack.mjs. Do not edit.\n// Metro needs static require() calls, so every pre-recorded phrase is listed.\n\nexport const VOICE_PACK = {\n${keys
    .map((k) => `  '${k}': require('../../assets/voice/${k}.mp3'),`)
    .join('\n')}\n}\n`
)
console.log(`pack: ${keys.length} files`)
if (failed.length) {
  console.log('FAILED:')
  failed.forEach(([t, e]) => console.log(' ', t, '->', e))
}
